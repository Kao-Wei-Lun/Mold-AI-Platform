function initialLocale(): Locale {
  if (typeof window === "undefined") return "en";
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === "en" || stored === "zh-TW") return stored;
  } catch {
    // A blocked storage policy must not prevent the Engineering Web from loading.
  }
  return window.navigator.language.toLowerCase().startsWith("zh") ? "zh-TW" : "en";
}

const locale = ref<Locale>(initialLocale());

function interpolate(message: string, params: MessageParams = {}): string {
  return message.replace(/\{(\w+)\}/g, (match, name: string) => String(params[name] ?? match));
}

export function translate(key: string, params?: MessageParams): string {
  const message = locale.value === "zh-TW" ? zhTW[key] || key : key;
  return interpolate(message, params);
}

export function setLocale(next: Locale): void {
  locale.value = next;
  if (typeof window !== "undefined") {
    try {
      window.localStorage.setItem(STORAGE_KEY, next);
    } catch {
      // The in-memory preference still works when browser storage is unavailable.
    }
    document.documentElement.lang = next;
  }
}

export function useI18n() {
  return {
    locale,
    isChinese: computed(() => locale.value === "zh-TW"),
    setLocale,
    t: translate,
  };
}

if (typeof document !== "undefined") document.documentElement.lang = locale.value;
